"""
Aura Farming — training/calibrate_model.py
===========================================
Fit temperature scaling calibration on the validation set.

Phase 5 Implementation: COMPLETE
─────────────────────────────────
This script performs post-hoc probability calibration using temperature scaling:
  1. Loads the trained MobileNetV3 model checkpoint.
  2. Loads the validation manifest (data/splits/val_manifest.csv).
     CRITICAL SCIENTIFIC SAFETY:
       The TEST set (data/splits/test_manifest.csv) is NEVER touched here.
       Calibration parameters must be strictly fitted on validation data.
  3. Preprocesses validation images identically to training/inference.
  4. Generates raw validation predictions.
  5. Fits optimal temperature T > 0 by minimizing Negative Log-Likelihood.
  6. Computes ECE, NLL, and Brier score before and after calibration.
  7. Persists calibration parameters to models/mobilenetv3_calibration.json
     and saves an evaluation report to reports/calibration_report.json.

Usage:
    # Run calibration with defaults from config.yaml:
    python training/calibrate_model.py

    # Override checkpoint path:
    python training/calibrate_model.py --model-path models/mobilenetv3_phase_a.keras

    # Run self-test verification (validates calibration pipeline with synthetic validation data):
    python training/calibrate_model.py --self-test
"""

